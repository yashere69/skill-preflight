"""Score description-change alerts against eval/description_edits.yaml.

python tools/eval_diff.py      # writes results/description-edits.md
"""

from __future__ import annotations

from pathlib import Path

import yaml

from skill_preflight.lock import description_change

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    cases = yaml.safe_load((ROOT / "eval" / "description_edits.yaml").read_text())
    rows, tp, fp, fn, tn = [], 0, 0, 0, 0
    for c in cases:
        change = description_change(c["before"], c["after"])
        alert = change.level == "high"
        tp += alert and c["risky"]
        fp += alert and not c["risky"]
        fn += (not alert) and c["risky"]
        tn += (not alert) and not c["risky"]
        mark = "ok" if alert == c["risky"] else "MISS" if c["risky"] else "FALSE ALARM"
        rows.append(
            f"| {mark} | {'risky' if c['risky'] else 'benign'} | {change.level} | {change.what} |"
        )
    lines = [
        "# Description-edit alerts",
        "",
        f"Generated by `python tools/eval_diff.py` from {len(cases)} hand-written edits "
        f"({fp + tn} benign, {tp + fn} risky). An alert means `diff` rated the change `high`.",
        "",
        f"Risky edits alerted: **{tp}/{tp + fn}**. Benign edits alerted: **{fp}/{fp + tn}**.",
        "",
        "| Result | Label | Level | Reason |",
        "|---|---|---|---|",
        *rows,
    ]
    out = ROOT / "results" / "description-edits.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
